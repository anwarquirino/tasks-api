import { drizzle as drizzlePg } from 'drizzle-orm/node-postgres';
import { migrate as migratePg } from 'drizzle-orm/node-postgres/migrator';
import type { PgDatabase, PgQueryResultHKT } from 'drizzle-orm/pg-core';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import type { Env } from '../config/env.js';
import * as schema from './schema.js';

export type Schema = typeof schema;

/** Driver-agnostic database type: works for both node-postgres and PGlite. */
export type Database = PgDatabase<PgQueryResultHKT, Schema>;

export type DbDriver = Env['DB_DRIVER'];

export interface DatabaseHandle {
  db: Database;
  driver: DbDriver;
  /** Applies the SQL migrations generated by drizzle-kit in the `drizzle/` folder. */
  migrate(): Promise<void>;
  close(): Promise<void>;
}

const MIGRATIONS_FOLDER = fileURLToPath(new URL('../../drizzle', import.meta.url));

/**
 * Creates the database connection for the configured driver.
 *
 * - `pg`: a node-postgres pool pointing at DATABASE_URL (dev/prod).
 * - `pglite`: an in-memory PostgreSQL via PGlite (tests and local experiments),
 *   loaded lazily because it is a devDependency.
 */
export async function createDb(
  env: Pick<Env, 'DB_DRIVER' | 'DATABASE_URL'>,
): Promise<DatabaseHandle> {
  if (env.DB_DRIVER === 'pglite') {
    return createPgliteDb();
  }

  if (!env.DATABASE_URL) {
    throw new Error('DATABASE_URL é obrigatória quando DB_DRIVER=pg');
  }

  return createPgDb(env.DATABASE_URL);
}

function createPgDb(connectionString: string): DatabaseHandle {
  const pool = new pg.Pool({ connectionString });
  const db = drizzlePg(pool, { schema });

  return {
    db,
    driver: 'pg',
    migrate: () => migratePg(db, { migrationsFolder: MIGRATIONS_FOLDER }),
    close: () => pool.end(),
  };
}

async function createPgliteDb(): Promise<DatabaseHandle> {
  const [{ PGlite }, { drizzle }, { migrate }] = await Promise.all([
    import('@electric-sql/pglite'),
    import('drizzle-orm/pglite'),
    import('drizzle-orm/pglite/migrator'),
  ]);

  const client = new PGlite();
  const db = drizzle(client, { schema });

  return {
    db,
    driver: 'pglite',
    migrate: () => migrate(db, { migrationsFolder: MIGRATIONS_FOLDER }),
    close: () => client.close(),
  };
}
